export const FORMULA_BANK: Bank = {
  "8": CLASS_8,
  "9": CLASS_9,
  "10": CLASS_10,
  "11": CLASS_11,
  "12": CLASS_12,
};

/** The extra entries this bank holds for one chapter of one class. */
export function bankFor(grade: GradeId, chapter: string): CheatEntry[] {
  return FORMULA_BANK[grade]?.[chapter] ?? [];
}

/**
 * A chapter's own entries, then the bank's, duplicates removed by title.
 *
 * Title is the dedupe key because it is what the sheet prints: two entries
 * with the same name are the same result however differently the LaTeX was
 * written, and printing both is how a cheat-sheet starts to look padded.
 */
export function cheatWithBank(
  grade: GradeId,
  chapter: string,
  base: CheatEntry[],
): CheatEntry[] {
  const seen = new Set<string>();
  const out: CheatEntry[] = [];
  for (const entry of [...base, ...bankFor(grade, chapter)]) {
    const key = entry.title.trim().toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(entry);
  }
  return out;
}
