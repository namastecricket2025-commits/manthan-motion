import type { CheatEntry, GradeId } from "./mathlab";

/**
 * The formula bank.
 *
 * The chapter data in `mathlab.ts` carries the three or four governing
 * relations the solver reasons with — enough to teach from, not enough to
 * revise from. A formula sheet that stops there tells a Class 12 student that
 * the chapter on integrals contains four integrals.
 *
 * So this file is the revision layer: the standard results a student is
 * actually examined on, chapter by chapter and class by class, authored in
 * LaTeX and kept separate from the solver data so neither has to bend to fit
 * the other. `cheatWithBank` merges it into a chapter's own entries and drops
 * duplicates by title, so a result that is already in the chapter is never
 * printed twice.
 *
 * Everything here is a standard statement from the NCERT/CBSE sequence for
 * Classes 8 to 12 (and the equivalent ICSE/IB/IGCSE outcomes). Nothing is
 * invented to make a chapter look fuller: where a topic has a short list of
 * real results, the list is short.
 */

const f = (title: string, latex: string, note?: string): CheatEntry => ({
  kind: "formula",
  title,
  latex,
  note,
});

const t = (title: string, latex: string, note?: string): CheatEntry => ({
  kind: "theorem",
  title,
  latex,
  note,
});

const d = (title: string, latex: string, note?: string): CheatEntry => ({
  kind: "definition",
  title,
  latex,
  note,
});

type Bank = Record<GradeId, Record<string, CheatEntry[]>>;

